// build-map-path.mjs — turn Natural Earth's coastlines into one SVG path, once, at build time.
//
//   node scripts/video/build-map-path.mjs            # writes video-templates/world-path.json
//   node scripts/video/build-map-path.mjs --check    # verify the committed file, fetch nothing
//
// WHY BUILD TIME AND NOT RENDER TIME. The upstream HyperFrames `world-map` block loads d3,
// topojson-client, gsap AND the atlas itself from a CDN on every render. That turns "offline
// means missing fonts" into "offline means a blank map", and it puts four network round trips
// into a step that otherwise has none. Running this once and committing ~30 KB of path data
// costs the repo less than one of those downloads costs a render.
//
// TopoJSON is decoded by hand here, in about forty lines, rather than by adding a dependency:
// arcs are delta-encoded integer pairs, `transform` scales them back to degrees, and a
// geometry is a list of arc indices where a negative index means "that arc, reversed".
//
// PROVENANCE, because the map is someone else's work:
//   Natural Earth 1:110m Admin 0 — PUBLIC DOMAIN, no permission needed
//     https://www.naturalearthdata.com/about/terms-of-use/
//   redistributed as TopoJSON by topojson/world-atlas — ISC
//     https://github.com/topojson/world-atlas
//
// ENV: none. Needs network only without --check.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const KIT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = path.join(KIT, "video-templates", "world-path.json");
const SRC = "https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json";

/** Equirectangular: longitude and latitude map straight onto x and y. */
export const project = (lon, lat) => [((lon + 180) / 360) * 1000, ((90 - lat) / 180) * 500];

/** Decode one TopoJSON arc into absolute [lon, lat] pairs. */
function decodeArc(arc, transform) {
  const [sx, sy] = transform.scale;
  const [tx, ty] = transform.translate;
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * sx + tx, y * sy + ty];
  });
}

/**
 * Every ring of the `land` collection as an SVG path.
 *
 * A negative arc index means the arc traversed backwards, encoded as ~i — so ~(-3) is 2, and
 * the points come out reversed. Getting that wrong produces a map that looks almost right,
 * with coastlines that double back on themselves.
 */
export function landPath(topology, decimals = 1) {
  const arcs = topology.arcs.map((a) => decodeArc(a, topology.transform));
  const land = topology.objects.land;
  const geoms = land.type === "GeometryCollection" ? land.geometries : [land];

  const out = [];
  for (const g of geoms) {
    const polygons = g.type === "MultiPolygon" ? g.arcs : [g.arcs];
    for (const poly of polygons) {
      for (const ring of poly) {
        const pts = [];
        for (const idx of ring) {
          const seg = idx < 0 ? arcs[~idx].slice().reverse() : arcs[idx];
          // Consecutive arcs share an endpoint; keeping both draws a zero-length segment.
          for (const p of seg) {
            if (pts.length && pts[pts.length - 1][0] === p[0] && pts[pts.length - 1][1] === p[1]) continue;
            pts.push(p);
          }
        }
        if (pts.length < 3) continue;
        const d = pts
          .map(([lon, lat], i) => {
            const [x, y] = project(lon, lat);
            return `${i ? "L" : "M"}${x.toFixed(decimals)},${y.toFixed(decimals)}`;
          })
          .join("");
        out.push(`${d}Z`);
      }
    }
  }
  return out.join("");
}

// ── CLI ───────────────────────────────────────────────────────────────────────
if (process.argv[1] && import.meta.url === (await import("node:url")).pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes("--check");
  try {
    if (check) {
      const have = JSON.parse(fs.readFileSync(OUT, "utf8"));
      if (!have.path?.startsWith("M")) throw new Error("path does not start with a moveto");
      const rings = (have.path.match(/M/g) ?? []).length;
      console.log(`[map] ✓ ${rings} rings, ${(have.path.length / 1024).toFixed(0)} KB of path data`);
      console.log(`[map]   viewBox ${have.viewBox} · source ${have.source}`);
      process.exitCode = 0;
    } else {
      console.log(`[map] fetching ${SRC}`);
      const res = await fetch(SRC, { signal: AbortSignal.timeout(60000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const topo = await res.json();
      const d = landPath(topo);
      fs.writeFileSync(
        OUT,
        JSON.stringify(
          {
            _comment: [
              "World coastlines as one SVG path, generated by scripts/video/build-map-path.mjs.",
              "Do not hand-edit. Equirectangular projection into a 1000x500 viewBox, so a",
              "marker at (lon, lat) sits at x = (lon+180)/360*1000, y = (90-lat)/180*500.",
              "",
              "Committed rather than fetched at render time: the upstream HyperFrames world-map",
              "block pulls d3, topojson-client, gsap and this atlas from a CDN on EVERY render.",
            ],
            source: "Natural Earth 1:110m (public domain) via topojson/world-atlas (ISC)",
            viewBox: "0 0 1000 500",
            path: d,
          },
          null,
          2,
        ) + "\n",
        "utf8",
      );
      const rings = (d.match(/M/g) ?? []).length;
      console.log(`[map] ✓ ${rings} rings, ${(d.length / 1024).toFixed(0)} KB → ${path.relative(process.cwd(), OUT)}`);
    }
  } catch (e) {
    console.error(`[map] ✗ ${e.message}`);
    process.exitCode = 1;
  }
}
